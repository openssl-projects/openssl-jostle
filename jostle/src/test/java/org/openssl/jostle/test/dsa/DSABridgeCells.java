package org.openssl.jostle.test.dsa;

import org.junit.jupiter.api.Assertions;
import org.openssl.jostle.jcajce.provider.ErrorCode;
import org.openssl.jostle.jcajce.provider.JostleProvider;
import org.openssl.jostle.jcajce.provider.ProviderCapabilityException;
import org.openssl.jostle.jcajce.provider.dsa.DSAServiceNI;
import org.openssl.jostle.jcajce.provider.md.MDServiceNI;
import org.openssl.jostle.jcajce.spec.SpecNI;
import org.openssl.jostle.rand.RandSource;
import org.openssl.jostle.test.TestUtil;

import java.math.BigInteger;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.Security;
import java.security.interfaces.DSAPrivateKey;
import java.security.interfaces.DSAPublicKey;

/**
 * DSA bridge cells shared by the base and FIPS limit tests: each takes the NI set under test, so one body pins
 * both interface libraries on whichever bridge the leg loads. Keys are imported from components, because a FIPS
 * module may refuse to generate them.
 */
public final class DSABridgeCells
{
    private static final RandSource RND = TestUtil.RNDSrc;
    private static final String DIGEST = "SHA2-256";

    private static KeyPair keyPair;

    private DSABridgeCells()
    {
    }

    /** One 2048/256 key pair per JVM, generated by the base provider. */
    private static synchronized KeyPair keyPair() throws Exception
    {
        if (keyPair == null)
        {
            if (Security.getProvider(JostleProvider.PROVIDER_NAME) == null)
            {
                Security.addProvider(new JostleProvider());
            }
            KeyPairGenerator kpg = KeyPairGenerator.getInstance("DSA", JostleProvider.PROVIDER_NAME);
            kpg.initialize(2048);
            keyPair = kpg.generateKeyPair();
        }
        return keyPair;
    }

    private static int code(ErrorCode c)
    {
        return c.getCode();
    }

    private static byte[] magnitude(BigInteger v)
    {
        byte[] raw = v.toByteArray();
        if (raw.length > 1 && raw[0] == 0)
        {
            byte[] out = new byte[raw.length - 1];
            System.arraycopy(raw, 1, out, 0, out.length);
            return out;
        }
        return raw;
    }

    private static long importPrivate(DSAServiceNI dsa) throws Exception
    {
        DSAPrivateKey priv = (DSAPrivateKey) keyPair().getPrivate();
        return dsa.makePrivateFromComponents(magnitude(priv.getParams().getP()), magnitude(priv.getParams().getQ()),
                magnitude(priv.getParams().getG()), magnitude(priv.getX()), RND);
    }

    /**
     * A key spec or a digest context as the signer, and a signer as a key spec, are each refused with a typed code
     * at every entry that takes the handle; a dispose of the wrong kind frees nothing.
     */
    public static void wrongKindHandlesAreRefused(DSAServiceNI dsa, SpecNI spec, MDServiceNI md) throws Exception
    {
        int ctxWrong = code(ErrorCode.JO_DSA_CTX_WRONG_KIND);
        int specWrong = code(ErrorCode.JO_KEY_SPEC_WRONG_KIND);
        long keyRef = importPrivate(dsa);
        long signerRef = dsa.allocateSigner();
        long mdRef = md.allocateDigest("SHA256", 0);
        try
        {
            for (long bad : new long[]{keyRef, mdRef})
            {
                Assertions.assertEquals(ctxWrong, dsa.ni_initSign(bad, keyRef, DIGEST, RND));
                Assertions.assertEquals(ctxWrong, dsa.ni_initVerify(bad, keyRef, DIGEST));
                Assertions.assertEquals(ctxWrong, dsa.ni_update(bad, new byte[1], 0, 1));
                Assertions.assertEquals(ctxWrong, dsa.ni_sign(bad, null, 0, RND));
                Assertions.assertEquals(ctxWrong, dsa.ni_sign(bad, new byte[64], 0, RND));
                Assertions.assertEquals(ctxWrong, dsa.ni_verify(bad, new byte[8], 8, RND));
            }
            Assertions.assertEquals(specWrong, dsa.ni_initSign(signerRef, signerRef, DIGEST, RND));
            Assertions.assertEquals(specWrong, dsa.ni_initSign(signerRef, mdRef, DIGEST, RND));
            Assertions.assertEquals(specWrong, dsa.ni_initVerify(signerRef, signerRef, DIGEST));
            Assertions.assertEquals(specWrong, dsa.ni_getComponent(signerRef, DSAServiceNI.COMP_P, null));
            int[] err = new int[1];
            Assertions.assertEquals(0L, dsa.ni_generateKeyPair(signerRef, err, RND));
            Assertions.assertEquals(specWrong, err[0]);

            IllegalArgumentException e = Assertions.assertThrows(IllegalArgumentException.class,
                    () -> dsa.update(keyRef, new byte[1], 0, 1));
            Assertions.assertEquals("handle is not a DSA signer context", e.getMessage());

            // A dispose of the wrong kind frees nothing: the handles still work afterwards.
            dsa.disposeSigner(keyRef);
            dsa.disposeSigner(mdRef);
            Assertions.assertEquals(0, dsa.ni_initVerify(signerRef, keyRef, DIGEST));
            Assertions.assertEquals(256, dsa.ni_getComponent(keyRef, DSAServiceNI.COMP_P, null));
            Assertions.assertEquals(32, md.ni_getDigestOutputLen(mdRef));
        }
        finally
        {
            md.dispose(mdRef);
            dsa.disposeSigner(signerRef);
            spec.dispose(keyRef);
        }
    }

    /**
     * An empty digest name, one with an embedded NUL, names the library cannot fetch, and MD5, which a default
     * provider fetches and refuses for DSA, answer the same code at both entries and on both bridges; a null name
     * keeps its own code. The refusal names the digest and the direction.
     */
    public static void unusableDigestNamesAreRefused(DSAServiceNI dsa, SpecNI spec) throws Exception
    {
        int notServed = code(ErrorCode.JO_DSA_DIGEST_NOT_SUPPORTED);
        long keyRef = importPrivate(dsa);
        long signerRef = dsa.allocateSigner();
        try
        {
            for (String name : new String[]{"", DIGEST + "\u0000x", "none", "NOPE", "MD5"})
            {
                String label = name.replace("\u0000", "\\0");
                Assertions.assertEquals(notServed, dsa.ni_initSign(signerRef, keyRef, name, RND), label);
                Assertions.assertEquals(notServed, dsa.ni_initVerify(signerRef, keyRef, name), label);
            }
            int nullName = code(ErrorCode.JO_NAME_IS_NULL);
            Assertions.assertEquals(nullName, dsa.ni_initSign(signerRef, keyRef, null, RND));
            Assertions.assertEquals(nullName, dsa.ni_initVerify(signerRef, keyRef, null));

            ProviderCapabilityException e = Assertions.assertThrows(ProviderCapabilityException.class,
                    () -> dsa.initSign(signerRef, keyRef, "MD5", RND));
            Assertions.assertEquals("the loaded provider does not sign DSA with MD5", e.getMessage());
            e = Assertions.assertThrows(ProviderCapabilityException.class,
                    () -> dsa.initVerify(signerRef, keyRef, "MD5"));
            Assertions.assertEquals("the loaded provider does not verify DSA with MD5", e.getMessage());

            // The JDK spelling, OpenSSL's own and the raw path still verify.
            for (String name : new String[]{"SHA-256", DIGEST, "NONE"})
            {
                Assertions.assertEquals(0, dsa.ni_initVerify(signerRef, keyRef, name), name);
            }
        }
        finally
        {
            dsa.disposeSigner(signerRef);
            spec.dispose(keyRef);
        }
    }

    /**
     * y outside [2, p-2] or outside the subgroup, x outside [1, q-1], an even p and g = 1 are refused at import with
     * typed codes; the boundary values inside the ranges import.
     */
    public static void keyValuesAreRangeChecked(DSAServiceNI dsa, SpecNI spec) throws Exception
    {
        DSAPrivateKey priv = (DSAPrivateKey) keyPair().getPrivate();
        BigInteger p = priv.getParams().getP();
        BigInteger q = priv.getParams().getQ();
        BigInteger g = priv.getParams().getG();
        BigInteger y = ((DSAPublicKey) keyPair().getPublic()).getY();
        int pubBad = code(ErrorCode.JO_DSA_PUBLIC_VALUE_INVALID);
        int privBad = code(ErrorCode.JO_DSA_PRIVATE_VALUE_INVALID);
        int[] err = new int[1];

        // y = 2 is inside the range and outside the subgroup.
        for (BigInteger bad : new BigInteger[]{BigInteger.ZERO, BigInteger.ONE, BigInteger.valueOf(2),
                p.subtract(BigInteger.ONE), p})
        {
            Assertions.assertEquals(0L, dsa.ni_makePublicFromComponents(magnitude(p), magnitude(q), magnitude(g),
                    magnitude(bad), err), bad.toString(16));
            Assertions.assertEquals(pubBad, err[0], bad.toString(16));
        }
        Assertions.assertEquals(0L, dsa.ni_makePublicFromComponents(magnitude(p.subtract(BigInteger.ONE)),
                magnitude(q), magnitude(g), magnitude(y), err));
        Assertions.assertEquals(pubBad, err[0], "even p");
        Assertions.assertEquals(0L, dsa.ni_makePublicFromComponents(magnitude(p), magnitude(q),
                magnitude(BigInteger.ONE), magnitude(BigInteger.ONE), err));
        Assertions.assertEquals(pubBad, err[0], "g = 1");

        for (BigInteger bad : new BigInteger[]{BigInteger.ZERO, q, q.add(BigInteger.ONE)})
        {
            Assertions.assertEquals(0L, dsa.ni_makePrivateFromComponents(magnitude(p), magnitude(q), magnitude(g),
                    magnitude(bad), err, RND), bad.toString(16));
            Assertions.assertEquals(privBad, err[0], bad.toString(16));
        }

        IllegalArgumentException e = Assertions.assertThrows(IllegalArgumentException.class,
                () -> dsa.makePublicFromComponents(magnitude(p), magnitude(q), magnitude(g), magnitude(p)));
        Assertions.assertEquals("DSA y is outside its range or outside the subgroup of order q", e.getMessage());
        e = Assertions.assertThrows(IllegalArgumentException.class,
                () -> dsa.makePrivateFromComponents(magnitude(p), magnitude(q), magnitude(g), magnitude(q), RND));
        Assertions.assertEquals("DSA x is outside its range: [1, q-1]", e.getMessage());

        // The values just inside the ranges import.
        long pubRef = dsa.makePublicFromComponents(magnitude(p), magnitude(q), magnitude(g), magnitude(y));
        spec.dispose(pubRef);
        for (BigInteger good : new BigInteger[]{BigInteger.ONE, q.subtract(BigInteger.ONE)})
        {
            long ref = dsa.makePrivateFromComponents(magnitude(p), magnitude(q), magnitude(g), magnitude(good), RND);
            Assertions.assertNotEquals(0L, ref, good.toString(16));
            spec.dispose(ref);
        }
    }
}
